"use client";

/**
 * TanStack Query hooks for the homepage cards.
 *
 * Three rules this module exists to hold:
 *
 * - **One cache identity per served answer.** Presets are keyed by use case and
 *   currency; a detail is keyed by `recommendation_id` AND `catalog_version`, so
 *   a catalog bump can never answer with a price that was invalidated.
 * - **No `placeholderData`.** A changed key must return `data: undefined` while
 *   pending, so the previous selection's pills, score and badge disappear the
 *   moment the visitor changes an answer.
 * - **The vocabulary call never blocks the page.** `meta/options` only upgrades
 *   the currency and the use-case list; a failure leaves the fallbacks in place
 *   and renders nothing about itself.
 *
 * The `queryFn`s deliberately do NOT consume TanStack Query's `AbortSignal`, and
 * that is a measured decision rather than an oversight. Forwarding it made v5
 * abort and re-issue a read when React StrictMode mounted, unmounted and
 * remounted a tree in `next dev`: one Gaming ladder read became two, and the
 * four e2e specs that pin "one read per cache identity" failed. The abort only
 * ever saved dev-time bandwidth, so the dedupe contract wins. Measured and
 * reverted 2026-11-08 — see `docs/milestone-4-quality-report.md` (M4-F1).
 */
import { useQuery } from "@tanstack/react-query";

import { getBrowserApiClient } from "@/lib/api/client";
import { unwrapApiResult } from "@/lib/api/errors";

import type { HomeUseCase } from "./builds";

/**
 * The vocabulary read lives in `lib/api/meta` because the configurator needs the
 * same answer; re-exported here so the homepage keeps its single entry point (and
 * this module stays the one a homepage test has to mock).
 */
export { META_STALE_TIME_MS, useMetaOptions } from "@/lib/api/meta";
export type { MetaOptions } from "@/lib/api/meta";

/** Presets and details are regenerated by a pipeline; a minute is cheap. */
export const PRESET_STALE_TIME_MS = 60_000;

/** `["presets", useCase, currency]` — a currency change is a different answer. */
export function presetsQueryKey(useCase: HomeUseCase, currency: string) {
  return ["presets", useCase, currency] as const;
}

/** `["recommendation", id, catalogVersion]` — the key §6 of the spec pins. */
export function recommendationQueryKey(recommendationId: string, catalogVersion: string | null) {
  return ["recommendation", recommendationId, catalogVersion] as const;
}

/** One preset ladder for one use case. The route takes exactly one use case. */
export function usePresets(useCase: HomeUseCase, currency: string) {
  return useQuery({
    queryKey: presetsQueryKey(useCase, currency),
    staleTime: PRESET_STALE_TIME_MS,
    queryFn: async () =>
      unwrapApiResult(
        await getBrowserApiClient().GET("/v1/presets", {
          params: { query: { use_case: useCase, currency } },
        }),
      ),
  });
}

/**
 * The detail behind one selected preset. Disabled until a preset exists, so an
 * empty slot never issues a request for the string "null".
 */
export function useRecommendationDetail(
  recommendationId: string | null,
  catalogVersion: string | null,
) {
  return useQuery({
    queryKey: recommendationQueryKey(recommendationId ?? "", catalogVersion),
    staleTime: PRESET_STALE_TIME_MS,
    enabled: recommendationId !== null,
    queryFn: async () => {
      if (recommendationId === null) {
        throw new Error("recommendation detail requested without an id");
      }

      return unwrapApiResult(
        await getBrowserApiClient().GET("/v1/recommendations/{id}", {
          params: { path: { id: recommendationId } },
        }),
      );
    },
  });
}
