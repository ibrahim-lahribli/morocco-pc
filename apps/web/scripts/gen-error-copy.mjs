#!/usr/bin/env node
/**
 * apps/web/scripts/gen-error-copy.mjs — generate the error boundary's copy.
 *
 * WHY THIS FILE EXISTS. `app/[locale]/error.tsx` is the app's only client
 * component that cannot be handed its copy as props: Next renders an error
 * boundary IN PLACE of the segment, so no server parent reads the catalogue for
 * it. The obvious fix — mount `NextIntlClientProvider` — was measured and
 * REJECTED: it added **15 845 B** of script to the result route (168 710 ->
 * 184 555 B against a 174 080 B budget) and took LCP from 2 494 to 2 643 ms.
 * Two catalogues and an ICU runtime are not worth seven sentences.
 *
 * So the copy is mirrored into a plain object at build time, the same way this
 * repo generates `docs/DECISION_INDEX.md` and `docs/SCHEMA_REFERENCE.md`: the
 * JSON stays the single source of truth, the generated consumer costs a few
 * hundred bytes, and `npm run check:i18n` FAILS when the two drift apart.
 * Never edit the generated file by hand.
 *
 * Usage: `node scripts/gen-error-copy.mjs` rewrites it; `--check` exits 1 when
 * it is stale.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
export const OUT = path.join(ROOT, "lib", "i18n", "error-copy.generated.ts");
const LOCALES = ["fr", "ar"];

/** The generated file's exact contents, from the catalogues. */
export function generate() {
  const blocks = LOCALES.map((locale) => {
    const file = path.join(ROOT, "messages", `${locale}.json`);
    const parsed = JSON.parse(fs.readFileSync(file, "utf8"));
    const errors = parsed.errors;
    if (errors === undefined) throw new Error(`messages/${locale}.json has no "errors" namespace`);
    const entries = Object.entries(errors).map(
      ([key, value]) => `      ${JSON.stringify(key)}: ${JSON.stringify(value)},`,
    );
    return `  ${locale}: {\n${entries.join("\n")}\n  },`;
  });

  return [
    "/**",
    " * GENERATED by `scripts/gen-error-copy.mjs` from the `errors` namespace of",
    " * `messages/fr.json` and `messages/ar.json`. NEVER edit by hand — edit the",
    " * catalogues and run `node scripts/gen-error-copy.mjs`. `npm run check:i18n`",
    " * fails while this file is stale.",
    " *",
    " * Why a generated object instead of `useTranslations`: the error boundary is",
    " * a client component that cannot receive props, and mounting",
    " * `NextIntlClientProvider` for it cost 15 845 B of script on the result route",
    " * (measured 2026-11-03) — over the whole 5 370 B margin twice. Seven sentences",
    " * do not need an ICU runtime.",
    " */",
    "export const ERROR_COPY = {",
    blocks.join("\n"),
    "} as const;",
    "",
    "export type ErrorCopy = (typeof ERROR_COPY)[keyof typeof ERROR_COPY];",
    "",
  ].join("\n");
}

const normalise = (text) => text.replace(/\r\n/g, "\n");

if (process.argv[1] !== undefined && path.basename(process.argv[1]) === "gen-error-copy.mjs") {
  const check = process.argv.includes("--check");
  const expected = normalise(generate());
  const actual = fs.existsSync(OUT) ? normalise(fs.readFileSync(OUT, "utf8")) : "";

  if (check) {
    if (actual !== expected) {
      console.error(
        "FAIL error-copy: lib/i18n/error-copy.generated.ts is stale — run `node scripts/gen-error-copy.mjs`",
      );
      process.exit(1);
    }
    console.log("PASS error-copy: generated copy matches messages/*.json");
  } else {
    fs.writeFileSync(OUT, expected, "utf8");
    console.log(`ok ${path.relative(ROOT, OUT).split(path.sep).join("/")} written`);
  }
}
